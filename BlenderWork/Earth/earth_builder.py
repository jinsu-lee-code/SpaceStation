def to_xy(lon, lat):
    return (lon + 180.0) / 360.0 * W, (90.0 - lat) / 180.0 * H


def fill(mask, poly, value):
    """짝홀 규칙으로 다각형 안을 채움 (행마다 가장자리 교차점 사이). 경도 180을 넘는 점은 −360 옮긴 사본도 채움."""
    if len(poly) < 3:
        return
    for shift in (0.0, -360.0, 360.0):
        pts = [to_xy(lon + shift, lat) for lon, lat in poly]
        xs = np.array([p[0] for p in pts]); ys = np.array([p[1] for p in pts])
        if xs.max() < 0 or xs.min() >= W:
            continue
        x2 = np.roll(xs, -1); y2 = np.roll(ys, -1)
        y0, y1 = int(max(0, math.floor(ys.min()))), int(min(H - 1, math.ceil(ys.max())))
        for row in range(y0, y1 + 1):
            yc = row + 0.5
            hit = ((ys <= yc) & (y2 > yc)) | ((y2 <= yc) & (ys > yc))
            if not hit.any():
                continue
            t = (yc - ys[hit]) / (y2[hit] - ys[hit])
            cross = np.sort(xs[hit] + t * (x2[hit] - xs[hit]))
            for a, b in zip(cross[0::2], cross[1::2]):
                c0, c1 = max(0, int(math.ceil(a - 0.5))), min(W - 1, int(math.floor(b - 0.5)))
                if c1 >= c0:
                    mask[row, c0:c1 + 1] = value


