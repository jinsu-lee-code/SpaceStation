NLON, NLAT = 128, 64
bm = bmesh.new()
uv_layer = bm.loops.layers.uv.new('UVMap')
grid = {}
for j in range(NLAT + 1):
    la_ = math.radians(-90 + 180.0 * j / NLAT)
    for i in range(NLON + 1):
        lo_ = math.radians(-180 + 360.0 * i / NLON)
        grid[i, j] = bm.verts.new((math.cos(la_) * math.cos(lo_), math.cos(la_) * math.sin(lo_), math.sin(la_)))
for j in range(NLAT):
    for i in range(NLON):
        if j == 0:
            vs = [grid[i, 0], grid[i + 1, 1], grid[i, 1]]
            uvs = [((i + 0.5) / NLON, 0.0), ((i + 1) / NLON, 1 / NLAT), (i / NLON, 1 / NLAT)]
        elif j == NLAT - 1:
            vs = [grid[i, j], grid[i + 1, j], grid[i, j + 1]]
            uvs = [(i / NLON, j / NLAT), ((i + 1) / NLON, j / NLAT), ((i + 0.5) / NLON, 1.0)]
        else:
            vs = [grid[i, j], grid[i + 1, j], grid[i + 1, j + 1], grid[i, j + 1]]
            uvs = [(i / NLON, j / NLAT), ((i + 1) / NLON, j / NLAT), ((i + 1) / NLON, (j + 1) / NLAT), (i / NLON, (j + 1) / NLAT)]
        f = bm.faces.new(vs)
        f.smooth = True
        for loop, uv in zip(f.loops, uvs):
            loop[uv_layer].uv = uv
