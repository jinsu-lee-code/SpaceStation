def shot(name, lon0, lat0, sun_lon, sun_lat):
    d = lambda lo_, la_: (math.cos(math.radians(la_)) * math.cos(math.radians(lo_)), math.cos(math.radians(la_)) * math.sin(math.radians(lo_)), math.sin(math.radians(la_)))
    p = [4.2 * c for c in d(lon0, lat0)]
    cam.location = p
    from mathutils import Vector
    cam.rotation_euler = (-Vector(p)).to_track_quat('-Z', 'Y').to_euler()
    s = Vector(d(sun_lon, sun_lat))
    sun.rotation_euler = (-s).to_track_quat('-Z', 'Y').to_euler()
    sc.render.filepath = os.path.join(HERE, 'preview', name + '.png')
    bpy.ops.render.render(write_still=True)


