def value_noise(p, seed):
    r = np.random.RandomState(seed)
    perm = r.permutation(256)
    vals = r.rand(256).astype(np.float32)
    pi = np.floor(p).astype(np.int64)
    f = p - pi
    w = f * f * (3 - 2 * f)
    def hsh(ix, iy, iz):
        return vals[perm[(perm[(perm[ix & 255] + iy) & 255] + iz) & 255]]
    ix, iy, iz = pi[..., 0], pi[..., 1], pi[..., 2]
    out = 0
    for dx in (0, 1):
        wx = w[..., 0] if dx else 1 - w[..., 0]
        for dy in (0, 1):
            wy = w[..., 1] if dy else 1 - w[..., 1]
            for dz in (0, 1):
                wz = w[..., 2] if dz else 1 - w[..., 2]
                out = out + wx * wy * wz * hsh(ix + dx, iy + dy, iz + dz)
    return out


def fbm(p, scale, octaves, seed):
    total, amp, norm = 0, 1.0, 0
    for o in range(octaves):
        total = total + amp * value_noise(p * scale * (2 ** o), seed + o * 17)
        norm += amp
        amp *= 0.5
    return total / norm


def blur(a, r):
    """상자 흐림 (가로는 감싸기)."""
    k = 2 * r + 1
    pad = np.concatenate([a[:, -r:], a, a[:, :r]], axis=1)
    c = np.cumsum(pad, axis=1); c = np.concatenate([np.zeros((a.shape[0], 1)), c], axis=1)
    a = (c[:, k:] - c[:, :-k]) / k
    pad = np.concatenate([np.repeat(a[:1], r, 0), a, np.repeat(a[-1:], r, 0)], axis=0)
    c = np.cumsum(pad, axis=0); c = np.concatenate([np.zeros((1, a.shape[1])), c], axis=0)
    return (c[k:] - c[:-k]) / k


def smooth(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0, 1)
    return t * t * (3 - 2 * t)


def box(lon0, lon1, lat0, lat1, soft):
    return smooth(0, soft, np.minimum.reduce([LON - lon0, lon1 - LON, LAT - lat0, lat1 - LAT]))


